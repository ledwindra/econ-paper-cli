"""Version-controlled pinned managed-runtime artifact data.

Kept as a plain Python module (not a JSON/data file) so it is always
included in built wheels/sdists with no separate packaging configuration —
see the issue #58 plan discussion on manifest representation.

Pins ``llama.cpp`` release ``b10199`` (the same release
``LlamaCppConfig``'s ``runtime_id``/``runtime_version_marker`` defaults
already assume) for macOS arm64, macOS x86_64, Linux x86_64, and Windows
x86_64 — the approved supported-platform matrix (macOS arm64 *and* x86_64,
per the posted issue #58 plan, so an Intel Mac is covered too, not just the
platforms this project's CI matrix happens to run). Each entry is the
standard upstream release asset for its platform: no CUDA, ROCm, or Vulkan
variant, and no GPU required, which is what the "no GPU requirement" product
guardrail asks for. That is not the same as shipping no accelerator support
-- the macOS arm64 asset bundles ``libggml-metal`` and both macOS assets
bundle ``libggml-blas``; Linux and Windows are CPU-only. See
``docs/artifact-licensing.md``. ``archive_size_bytes``/
``archive_sha256``/``bundle_member_checksums`` were computed directly from
the real release assets downloaded from the URLs below — every file actually
present in each archive is declared here, not merely computed at install
time, so a tampered file plus a rewritten receipt.json still fails
verification against this static, version-controlled anchor.

The verified values must never be taken from upstream documentation or a
release page: ``archive_size_bytes``, ``archive_sha256``, and every entry in
``bundle_member_checksums`` have to be computed locally from a real download
of the declared ``source_url``. The remaining fields — URL, platform,
architecture, archive format, version marker, and executable path — are
chosen when the pin is written and are not derived from downloaded bytes,
though the download is what confirms they are right. A wrong checksum makes
provisioning fail for every user on that platform at once. The managed-model
manifest states the same rule for the same reason.
"""

